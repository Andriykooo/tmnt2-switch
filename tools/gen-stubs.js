// Generates port/imports_gen.c: a weak default for every wasm import declared in gen/tmnt2.h.
// Each default logs its first few calls and returns 0, so real implementations in other
// files simply override them by defining the same symbol.
//
// usage: node gen-stubs.js gen/tmnt2.h port/imports-dump.tsv port/imports_gen.c
const fs = require('fs');

const [headerPath, dumpPath, outPath] = process.argv.slice(2);
const header = fs.readFileSync(headerPath, 'utf8');

// JS body of each import, used as a comment so the C side documents what it replaces.
const bodies = {};
for (const line of fs.readFileSync(dumpPath, 'utf8').split('\n')) {
  const [key, , body] = line.split('\t');
  if (key && key.startsWith('a.')) bodies[key.slice(2)] = (body || '').slice(0, 150);
}

// wasm2c mangles import names: "$" -> "0x24", "_" -> "0x5F".
function demangle(name) {
  return name.replace(/0x24/g, '$').replace(/0x5F/g, '_');
}

const decls = [...header.matchAll(/^(u32|u64|f32|f64|void) (w2c_a_[A-Za-z0-9]+)\(struct w2c_a\*((?:, (?:u32|u64|f32|f64))*)\);$/gm)];
const fmt = { u32: '%u', u64: '%llu', f32: '%g', f64: '%g' };
const cast = { u32: '', u64: '(unsigned long long)', f32: '(double)', f64: '' };

let out = `// GENERATED by tools/gen-stubs.js - do not edit. Override any import by defining it elsewhere.
#include "rt.h"

`;
const table = [];
for (const [, ret, fn, argList] of decls) {
  const types = argList ? argList.split(', ').filter(Boolean) : [];
  const params = types.map((t, i) => `${t} a${i}`);
  const sig = ['struct w2c_a* env', ...params].join(', ');
  const short = fn.slice('w2c_a_'.length);
  const js = demangle(short);
  const fmtArgs = types.map(t => fmt[t]).join(',');
  const callArgs = types.map((t, i) => `, ${cast[t]}a${i}`).join('');
  out += `// ${js}: ${(bodies[js] || '?').replace(/\*\//g, '* /')}\n`;
  out += `__attribute__((weak)) ${ret} ${fn}(${sig}) {\n`;
  out += `  RT_STUB_LOG("${js}", "(${fmtArgs})"${callArgs});\n`;
  if (ret !== 'void') out += `  return 0;\n`;
  out += `}\n\n`;
  table.push(js);
}

fs.writeFileSync(outPath, out);
console.log(`${decls.length} import stubs -> ${outPath}`);
